export function getCardImageUrl(folder, file) {
  return `/assets/cards/${folder}/${file}`;
}

/** Helper: shuffle array Fisher-Yates */
export function shuffleArray(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** Ambil N kartu acak dari kategori (untuk 1 ronde = 3 kartu) */
export function pickRandomCards(categoryCards, count = 3) {
  return shuffleArray(categoryCards).slice(0, count);
}

/** Buat set ronde dari pool kartu (setiap ronde ambil 3 kartu berbeda) */
export function buildRounds(categoryCards, totalRounds = 5, cardsPerRound = 3) {
  const pool = shuffleArray(categoryCards);
  const rounds = [];
  for (let i = 0; i < totalRounds; i++) {
    const startIdx = (i * cardsPerRound) % pool.length;
    const set = [];
    for (let j = 0; j < cardsPerRound; j++) {
      set.push(pool[(startIdx + j) % pool.length]);
    }
    rounds.push(set);
  }
  return rounds;
}
